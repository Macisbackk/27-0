/**
 * Writes data/era-coverage-2026-10.md: Super League 1996–2026 coverage before/after the Oct 2026
 * era-coverage fill. "Before" is data/era-coverage-before-2026-10.json (scripts/era-coverage-report.ts
 * on main before the fill); "after" is computed now.
 *
 * Run: bun scripts/era-coverage-md.ts
 */
import fs from "node:fs";
import path from "node:path";
import { buildCoverage, type CoverageRow } from "./era-coverage-report";

const ROOT = path.resolve(import.meta.dirname ?? __dirname, "..");
const D = (f: string) => path.join(ROOT, "data", f);
const before = JSON.parse(fs.readFileSync(D("era-coverage-before-2026-10.json"), "utf8")) as CoverageRow[];
const after = buildCoverage();
const fill = JSON.parse(fs.readFileSync(D("era-coverage-fill-2026-10-report.json"), "utf8")) as {
  cardsCreated: number;
  superseded: string[];
  unresolved: string[];
  clubSeasons: Record<string, { source: string; created: string[]; existing: number; unresolved: string[]; xiii: string }>;
};
const lineups = JSON.parse(fs.readFileSync(D("era-coverage-lineups-2026-10.json"), "utf8")) as Array<{ club: string; year: number; source: string; match: string }>;
const bios = JSON.parse(fs.readFileSync(D("era-coverage-new-players-2026-10.json"), "utf8")) as Record<string, { name?: string; nationality: string; dateOfBirth?: string; source: string }>;

const key = (r: { club: string; year: number }) => `${r.club}|${r.year}`;
const b = new Map(before.map((r) => [key(r), r]));
const cell = (r: CoverageRow | undefined) =>
  r ? `${r.spin ? "yes" : "no"} / ${r.own} / ${r.full13 ? "yes" : "no"} / ${r.full17 ? "yes" : "no"}` : "n/a";
const notable = (r: CoverageRow | undefined) => (r ? `${r.notables.filter((n) => n.card).length}/${r.notables.length}` : "");

function totals(rows: CoverageRow[]) {
  const hist = rows.filter((r) => r.year <= 2025);
  const nots = rows.flatMap((r) => r.notables);
  const award = (a: string) => {
    const s = nots.filter((n) => n.award === a);
    return `${s.filter((n) => n.card).length}/${s.length}`;
  };
  return {
    clubSeasons: rows.length,
    spinnable: rows.filter((r) => r.spin).length,
    histSpinnable: hist.filter((r) => r.spin).length,
    hist: hist.length,
    side: rows.filter((r) => r.side).length,
    anyOwn: rows.filter((r) => r.own > 0).length,
    own13: rows.filter((r) => r.own >= 13).length,
    full13: rows.filter((r) => r.full13).length,
    full17: rows.filter((r) => r.full17).length,
    ownCards: rows.reduce((n, r) => n + r.own, 0),
    spinOwnSlots: rows.reduce((n, r) => n + (r.spinOwn ?? 0), 0),
    spinSlots: rows.filter((r) => r.spin).length * 13,
    mos: award("Man of Steel"),
    dt: award("Dream Team"),
    lt: award("Lance Todd"),
    hs: award("Harry Sunderland"),
  };
}
const tb = totals(before);
const ta = totals(after);

const L: string[] = [];
L.push("# Super League era coverage, 1996–2026 (October 2026)");
L.push("");
L.push("Owner's question: are there gaps in years or players from the start of Super League?");
L.push("This report checks every club that actually played each Super League season against what the game has, then");
L.push("lists what was filled and what is still missing. Generated by `bun scripts/era-coverage-md.ts`; the per-season");
L.push("numbers come from `scripts/era-coverage-report.ts`.");
L.push("");
L.push("## How to read it");
L.push("");
L.push("- **Club list per season**: the final league tables from the Wikipedia `<year> Super League season` pages (already in");
L.push("  `data/era-rating-anchors.json`), plus Toronto Wolfpack 2020 (withdrew after six rounds, results expunged) and the");
L.push("  14 clubs of 2026. That is 388 club-seasons, 374 of them 1996–2025.");
L.push("- **Spin**: the club-season is an Era Classic spin pool (2026: a Classic Current pool).");
L.push("- **Own**: recruitable cards pinned to that exact club and season.");
L.push("- **13 / 17**: those own-season cards cover a full XIII by position (and 17 cards with a full XIII).");
L.push("- **Notable**: Man of Steel, Dream Team, Lance Todd and Harry Sunderland winners for that club that season");
L.push("  (Wikipedia, via `data/era-rating-anchors.json`) with a card for that exact club-season.");
L.push("");
L.push("## Headline numbers");
L.push("");
L.push("| | Before | After |");
L.push("|---|---|---|");
L.push(`| Club-seasons spinnable in Era Classic (1996–2025) | ${tb.histSpinnable}/${tb.hist} | ${ta.histSpinnable}/${ta.hist} |`);
L.push(`| Club-seasons spinnable incl. 2026 Classic | ${tb.spinnable}/${tb.clubSeasons} | ${ta.spinnable}/${ta.clubSeasons} |`);
L.push(`| Era starting-17 sides (Era Challenge Cup / One-per-club) | ${tb.side} | ${ta.side} |`);
L.push(`| Club-seasons with at least one own-season card | ${tb.anyOwn} | ${ta.anyOwn} |`);
L.push(`| Club-seasons with 13+ own-season cards | ${tb.own13} | ${ta.own13} |`);
L.push(`| Club-seasons whose own-season cards make a full XIII | ${tb.full13} | ${ta.full13} |`);
L.push(`| ... and a full 17 | ${tb.full17} | ${ta.full17} |`);
L.push(`| Own-season cards (all club-seasons) | ${tb.ownCards} | ${ta.ownCards} |`);
L.push(`| Spin-pool slots using that season's card | ${tb.spinOwnSlots}/${tb.spinSlots} | ${ta.spinOwnSlots}/${ta.spinSlots} |`);
L.push(`| Man of Steel seasons with a card | ${tb.mos} | ${ta.mos} |`);
L.push(`| Dream Team selections with a card for that club-season | ${tb.dt} | ${ta.dt} |`);
L.push(`| Lance Todd winners with a card for that club-season | ${tb.lt} | ${ta.lt} |`);
L.push(`| Harry Sunderland winners with a card for that club-season | ${tb.hs} | ${ta.hs} |`);
L.push("");
L.push(`Cards added: **${fill.cardsCreated}** season cards (${Object.keys(bios).length} of them players who had no card at all; the`);
L.push(`rest are existing players' cards for a season they were missing). ${fill.superseded.length} era-only cards ("-hist-era-",`);
L.push("never offered in spins) were superseded by the new card for the same player and season.");
L.push("");
L.push("## What was wrong");
L.push("");
L.push(`1. **Era Classic only spun ${tb.histSpinnable} of the ${tb.hist} historic club-seasons.** Spin pools come from verified XIIIs`);
L.push("   (`era-wikipedia-squads.json`, `sl-era-verified-squads.json`), and most seasons had none. Most did have a verified");
L.push("   starting 17 (`era-starting-17s.json`), but no spin XIII and few season cards.");
L.push(`2. **Most club-seasons had no card for that season.** Only ${tb.own13} club-seasons had 13+ own-season cards. Era sides filled`);
L.push("   the gaps with the player's nearest other season.");
L.push("3. **`super-league-club-years.json` was wrong.** It listed Hull KR 1999–2006 and 2017, Wakefield 1996–98, Huddersfield");
L.push("   1996–97 and 2002, Hull FC 1996–97, Salford 1996, 2003 and 2008, Castleford 2005 and 2007, London 2018 and 2020, Leigh");
L.push("   2018 and 2022, Bradford and York 2025 as Super League seasons. It missed Hull KR 2015–16, Widnes 2014–16, Leigh 2005");
L.push("   and 2021, London 2014 and 2024, and Salford 2025. Former clubs (Halifax, Sheffield, Oldham, Paris, Workington,");
L.push("   Gateshead, Crusaders, Toronto) were not in it at all. A London Broncos 2018 (Championship) pool was spinnable.");
L.push("4. **Former Super League clubs could not be spun.** Their cards were displayed as a current club (Sheffield → Leeds,");
L.push("   Halifax → Bradford, Paris → Catalans ...).");
L.push("");
L.push("## What changed");
L.push("");
L.push("- `data/super-league-club-years.json`: the real seasons for all 25 clubs (Wikipedia season tables).");
L.push("- `src/lib/clubs/super-league-display.ts`, `src/lib/players/era-teams.ts`: Halifax Panthers, Sheffield Eagles, Oldham RLFC,");
L.push("  Paris Saint-Germain RL, Workington Town, Gateshead Thunder, Crusaders RL and Toronto Wolfpack are era-playable");
L.push("  (historic-only) clubs, gated to their Super League seasons.");
L.push("- `scripts/fill-era-coverage-2026-10.ts` (re-runnable): for every club-season, a spin XIII from its verified starting 17");
L.push("  (jersey 1–13) when it had none that worked, and a season card for every player in the 17 and every award winner.");
L.push("  A new card copies the same player's nearest card (name, nationality, date of birth); position is the jersey he wore");
L.push("  in that 17; rating is his nearest card's rating moved along the age curve, never above his best card. Then");
L.push("  `scripts/build-era-ratings.ts` (honours-anchored peaks, season curve, club-finish layer) re-rated all era cards, so");
L.push("  the new cards sit on the same scale (Man of Steel seasons at the player's peak, Dream Team seasons at peak − 1 ...).");
L.push("- Club-seasons with no verified 17 got one from a real match line-up (`data/era-coverage-lineups-2026-10.json`, one");
L.push("  Rugby League Project match page or Wikipedia final page per side). Players with no card anywhere got a fresh card");
L.push("  only with a cited bio (`data/era-coverage-new-players-2026-10.json`: nationality, date of birth); they start at 82");
L.push("  (81 off the bench), the squad-player level, and the club-finish layer moves the side as a whole.");
L.push("- Halifax 2003 has no single line-up with every player verifiable, so its XIII is this season's cards at the");
L.push("  positions they played in the sourced line-ups.");
L.push("- `data/player-name-aliases.ts`: Andrew/Andy Farrell, Matty/Mat Ashurst, Robert/Rob Butler.");
L.push("- `src/lib/players/era-starting-17s.ts`: a starting 17 may spell positions out (\"FULLBACK\"), as Sheffield 1998 does.");
L.push("- `st-helens-hist-jason-hooper*`: loose forward (was stand-off), per the 2006 Grand Final line-up.");
L.push("- `gateshead-hist-martin-masella` (1998): filed under Gateshead, who were not in Super League until 1999; he played for");
L.push("  Leeds in 1998, so the card is Leeds Rhinos 1998.");
L.push("");
L.push("## Sources for added line-ups (club-seasons with no verified 17 before)");
L.push("");
L.push("| Club-season | Match | Source |");
L.push("|---|---|---|");
for (const l of [...lineups].sort((x, y) => x.year - y.year || x.club.localeCompare(y.club))) {
  L.push(`| ${l.club} ${l.year} | ${l.match} | ${l.source} |`);
}
L.push("");
L.push("Every other club-season's XIII and 17 come from its existing `era-starting-17s.json` entry, whose `source` field cites");
L.push("the Rugby League Project season page (or the verified 17s list); the new spin XIIIs carry the same source in");
L.push("`sl-era-verified-squads.json`. Award-season cards cite the Wikipedia award pages in their `sourceUrl`.");
L.push("");
L.push("## Players added with no previous card (bio sources)");
L.push("");
L.push("| Player | Nationality | Born | Source |");
L.push("|---|---|---|---|");
for (const [n, bio] of Object.entries(bios).sort(([a], [c]) => a.localeCompare(c))) {
  L.push(`| ${bio.name ?? n} | ${bio.nationality} | ${bio.dateOfBirth ?? "not given"} | ${bio.source} |`);
}
L.push("");
L.push("## Still missing");
L.push("");
const missing = after.filter((r) => !r.spin);
L.push(`${missing.length} club-seasons are still not spinnable:`);
L.push("");
L.push("| Club-season | Own-season cards | Why |");
L.push("|---|---|---|");
for (const r of missing) {
  const rep = fill.clubSeasons[key(r)];
  const why = rep?.unresolved.length
    ? `line-up sourced, but no card and no verifiable nationality/birth found for: ${[...new Set(rep.unresolved)].join(", ")}`
    : "no verified line-up found";
  L.push(`| ${r.club} ${r.year} | ${r.own} | ${why} |`);
}
L.push("");
const partial = Object.entries(fill.clubSeasons).filter(([k, r]) => r.unresolved.length && after.find((x) => key(x) === k)?.spin);
L.push("Spinnable, but some bench / award names still without a card for that season (so no era starting-17 side where");
L.push("the 17 is incomplete):");
L.push("");
for (const [k, r] of partial) L.push(`- ${k.replace("|", " ")}: ${[...new Set(r.unresolved)].join(", ")}`);
L.push("");
L.push("Other known gaps:");
L.push("");
L.push("- Widnes 2003 and 2004 era sides: their 17s list two different players called Julian O'Neill (the New Zealand");
L.push("  prop and the Australian stand-off); the database has one Julian O'Neill, so one slot cannot resolve.");
L.push("- Grand Final / Challenge Cup final starters, top try and point scorers and club captains were not checked season by");
L.push("  season (they would need a fetch per final and per season). Every club-season's verified 17 is now carded, which");
L.push("  covers the regular starters; the award checks above cover Man of Steel, Dream Team, Lance Todd and Harry Sunderland.");
L.push("- Fresh cards for unknown-level players start at 82/81. Their ratings are a squad-player default, not research.");
L.push("");
L.push("## Full table: every Super League club-season");
L.push("");
L.push("Cells: spin / own-season cards / full XIII / full 17. Notable = award winners with a card for that club-season.");
L.push("");
L.push("| Year | Club | Before | After | Notable before | Notable after |");
L.push("|---|---|---|---|---|---|");
for (const r of after) {
  const o = b.get(key(r));
  L.push(`| ${r.year} | ${r.club} | ${cell(o)} | ${cell(r)} | ${notable(o)} | ${notable(r)} |`);
}
L.push("");
fs.writeFileSync(D("era-coverage-2026-10.md"), L.join("\n"));
console.log(`wrote data/era-coverage-2026-10.md (${after.length} club-seasons; spinnable ${tb.spinnable} → ${ta.spinnable})`);
