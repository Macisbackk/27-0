/**
 * Calibration for the v1.19 side modes.
 *
 * One-Club XI — per club, drafts squads through the real spin flow restricted to that club
 * (pool variant "all", club filter) with the four tiers from scripts/lib/sim-draft.ts, and:
 *   • with --write, stores each club's anchors (mean squad rating of a typical and of a
 *     best-card-every-spin draft, typical chemistry) in src/lib/game/one-club-scale.ts;
 *   • prints the 27-0 rate per tier through the real season formula (formulaOverride).
 * Gauntlet — drafts Classic and Era squads per tier and prints mean sides beaten and the
 * clean-sweep (10/10) rate with GAUNTLET_FIELD_OFFSET.
 *
 * Run: RUNS=200 SEASONS=10 bun scripts/sim-one-club-gauntlet.ts [--write] [--skip-one-club] [--skip-gauntlet]
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { draftSquad, type DraftStrategy } from "./lib/sim-draft";
import { getAverageSquadRating } from "../src/lib/squad-analysis";
import { computeChemistry } from "../src/lib/game/chemistry";
import { simulateSeasonRecord } from "../src/lib/game/season-simulation";
import {
  getOneClubFormulaOverride,
  getOneClubOptions,
  getOneClubRuleFilter,
} from "../src/lib/game/one-club";
import { ONE_CLUB_SCALE } from "../src/lib/game/one-club-scale";
import {
  GAUNTLET_FIELD_OFFSET,
  gauntletScoreForChances,
  getGauntletChances,
  getGauntletOpponents,
} from "../src/lib/game/gauntlet";

const RUNS = Number(process.env.RUNS ?? 200);
const SEASONS = Number(process.env.SEASONS ?? 10);
const WRITE = process.argv.includes("--write");
const TIERS: DraftStrategy[] = ["weak", "random", "good", "best"];
const round = (n: number, d = 2) => Math.round(n * 10 ** d) / 10 ** d;

if (!process.argv.includes("--skip-one-club")) {
  const anchors: Record<string, { typicalRating: number; eliteRating: number; typicalChemistry: number }> = {};
  const draftsByClub = new Map<string, Map<DraftStrategy, ReturnType<typeof draftSquad>[]>>();
  for (const { club } of getOneClubOptions()) {
    const filter = getOneClubRuleFilter(club);
    const byTier = new Map<DraftStrategy, ReturnType<typeof draftSquad>[]>();
    for (const tier of TIERS) {
      const squads = Array.from({ length: RUNS }, (_, i) =>
        draftSquad(`oneclub-${club}-${tier}-${i}`, "era", tier, { spinVariant: "all", ruleFilter: filter })
      );
      byTier.set(tier, squads);
    }
    draftsByClub.set(club, byTier);
    const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
    anchors[club] = {
      typicalRating: round(mean(byTier.get("random")!.map(getAverageSquadRating))),
      eliteRating: round(mean(byTier.get("best")!.map(getAverageSquadRating))),
      typicalChemistry: round(mean(byTier.get("random")!.map((s) => computeChemistry(s).bonus))),
    };
  }
  if (WRITE) {
    const body = Object.entries(anchors)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([club, a]) =>
          `  ${JSON.stringify(club)}: { typicalRating: ${a.typicalRating}, eliteRating: ${a.eliteRating}, typicalChemistry: ${a.typicalChemistry} },`
      )
      .join("\n");
    writeFileSync(
      join(__dirname, "..", "src", "lib", "game", "one-club-scale.ts"),
      `/**
 * One-Club XI draft ladders — GENERATED by scripts/sim-one-club-gauntlet.ts --write
 * (${RUNS} simulated drafts per club per tier through the real spin flow). Do not edit by hand:
 * re-run after a ratings or roster change. typicalRating = mean squad rating of a typical draft
 * (a random offered card per spin), eliteRating = best offered card every spin, typicalChemistry
 * = mean chemistry of a typical draft (one-club sides link on club almost everywhere).
 */
import type { SimFormulaModeScale } from "./sim-formula";

export const ONE_CLUB_SCALE: Record<string, SimFormulaModeScale> = {
${body}
};
`
    );
    Object.assign(ONE_CLUB_SCALE, anchors);
    console.log(`wrote anchors for ${Object.keys(anchors).length} clubs`);
  }
  const totals = new Map<DraftStrategy, { perfect: number; wins: number; seasons: number }>();
  for (const [club, byTier] of draftsByClub) {
    const row: Record<string, unknown> = { club, ...anchors[club] };
    for (const tier of TIERS) {
      let perfect = 0;
      let wins = 0;
      let seasons = 0;
      for (const [i, squad] of byTier.get(tier)!.entries()) {
        const formulaOverride = getOneClubFormulaOverride(squad, club);
        for (let s = 0; s < SEASONS; s++) {
          const record = simulateSeasonRecord(squad, `oc-season-${club}-${tier}-${i}-${s}`, {
            mode: "era",
            formulaOverride,
          });
          const w = record.filter((r) => r === "W").length;
          wins += w;
          seasons++;
          if (w === 27) perfect++;
        }
      }
      row[`${tier}Perfect%`] = round((perfect / seasons) * 100, 1);
      row[`${tier}Wins`] = round(wins / seasons, 1);
      const t = totals.get(tier) ?? { perfect: 0, wins: 0, seasons: 0 };
      totals.set(tier, { perfect: t.perfect + perfect, wins: t.wins + wins, seasons: t.seasons + seasons });
    }
    console.log(JSON.stringify(row));
  }
  for (const [tier, t] of totals) {
    console.log(
      JSON.stringify({ oneClubAllClubs: tier, perfectPct: round((t.perfect / t.seasons) * 100, 2), avgWins: round(t.wins / t.seasons, 1) })
    );
  }
}

if (!process.argv.includes("--skip-gauntlet")) {
  console.log(
    JSON.stringify({
      gauntletOffset: GAUNTLET_FIELD_OFFSET,
      opponents: getGauntletOpponents().map((o) => `${o.label} ${o.squadRating} (${round(o.strength, 1)})`),
    })
  );
  for (const mode of ["classic", "era"] as const) {
    for (const tier of TIERS) {
      let beaten = 0;
      let sweeps = 0;
      let runs = 0;
      let analytic = 0;
      for (let i = 0; i < RUNS; i++) {
        const squad = draftSquad(`gauntlet-${mode}-${tier}-${i}`, mode, tier);
        const chances = getGauntletChances(squad, mode);
        analytic += chances.reduce((p, x) => p * x, 1);
        for (let s = 0; s < SEASONS; s++) {
          const score = gauntletScoreForChances(chances, `g-${mode}-${tier}-${i}-${s}`);
          beaten += score;
          runs++;
          if (score === chances.length) sweeps++;
        }
      }
      console.log(
        JSON.stringify({
          gauntlet: mode,
          tier,
          avgBeaten: round(beaten / runs, 2),
          sweepPct: round((sweeps / runs) * 100, 2),
          formulaSweepPct: round((analytic / RUNS) * 100, 2),
        })
      );
    }
  }
}
